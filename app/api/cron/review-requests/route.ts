/**
 * Cron: fires daily to send 7-day post-purchase review request emails.
 * Schedule via Vercel cron (vercel.json) or Supabase pg_cron.
 * Protected by CRON_SECRET header.
 */
export const dynamic = "force-dynamic";

import { NextRequest, NextResponse } from "next/server";
import { createElement } from "react";
import { createAdminClient } from "@/lib/supabase/admin";
import { resend } from "@/lib/resend";
import { ReviewRequestEmail } from "@/components/email-templates/review-request-email";
import type { Course } from "@/types";

const BASE = process.env.NEXT_PUBLIC_APP_URL ?? "https://hakeemrestro.shop";

export async function GET(req: NextRequest) {
  if (process.env.BILLDESK_ENV === "UAT") {
    return NextResponse.json({ error: "Scheduled email disabled in UAT" }, { status: 503 });
  }
  // Vercel cron sends `Authorization: Bearer $CRON_SECRET`.
  const secret = process.env.CRON_SECRET;
  const auth = req.headers.get("authorization");
  if (!secret?.trim() || auth !== `Bearer ${secret}`) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const supabase = createAdminClient();

  // Find paid parent orders created exactly 7 days ago (±12h window) with no review stub yet
  const from = new Date(Date.now() - 7.5 * 24 * 60 * 60 * 1000).toISOString();
  const to = new Date(Date.now() - 6.5 * 24 * 60 * 60 * 1000).toISOString();

  const { data: orders } = await supabase
    .from("orders")
    .select("id, customer_email, customer_name, course_id, courses(id, title, is_bundle)")
    .eq("status", "paid")
    .is("parent_order_id", null)
    .gte("created_at", from)
    .lte("created_at", to)
    .returns<Array<{
      id: string;
      customer_email: string;
      customer_name: string | null;
      course_id: string;
      courses: Pick<Course, "id" | "title" | "is_bundle"> | null;
    }>>();

  if (!orders || orders.length === 0) {
    return NextResponse.json({ processed: 0 });
  }

  let sent = 0;

  for (const order of orders) {
    const course = order.courses;
    if (!course || course.is_bundle) continue;

    // Check no review stub already exists for this order
    const { data: existing } = await supabase
      .from("reviews")
      .select("id")
      .eq("order_id", order.id)
      .maybeSingle();

    if (existing) continue;

    // Create the review stub row (token auto-generated by DB default)
    const { data: reviewRow } = await supabase
      .from("reviews")
      .insert({
        course_id: course.id,
        order_id: order.id,
        rating: 0,
        customer_name: order.customer_name ?? order.customer_email.split("@")[0],
        customer_email: order.customer_email,
      })
      .select("token")
      .single();

    if (!reviewRow) continue;

    const reviewUrl = `${BASE}/review/${reviewRow.token}`;

    try {
      await resend.emails.send({
        from: "Spice & Soul Academy <hello@hakeemrestro.shop>",
        replyTo: "hakeemrestro@gmail.com",
        to: order.customer_email,
        subject: `How did ${course.title} go? Share your experience`,
        react: createElement(ReviewRequestEmail, {
          customerName: order.customer_name ?? "there",
          courseTitle: course.title,
          reviewUrl,
        }),
      });

      sent++;
    } catch (err) {
      console.error(`Failed to send review request for order ${order.id}:`, err);
    }
  }

  return NextResponse.json({ processed: orders.length, sent });
}
